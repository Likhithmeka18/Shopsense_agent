"""
The Postman collection (docs/postman/) is generated by make_postman_collection.py from demo_api_client.CASES. These tests keep the
shipped files honest: they match the generator, cover every demo case plus the three validation cases, carry assertions on each
request, contain no secrets, and (when Node is installed) every embedded script at least compiles. They do NOT run Postman or the
HTTP server; that is the walkthrough in docs/DEPLOYMENT_CHECKLIST.md section B.
"""
import json
import shutil
import subprocess
from pathlib import Path

import make_postman_collection as mpc
from demo_api_client import CASES

DOCS = Path(__file__).resolve().parent.parent / "docs" / "postman"


def _load(name):
    return json.loads((DOCS / name).read_text(encoding="utf-8"))


def test_shipped_files_match_the_generator_so_they_cannot_drift():
    collection, environment = mpc.build()
    assert _load("ShopSense.postman_collection.json") == collection, "re-run: python make_postman_collection.py"
    assert _load("ShopSense.postman_environment.json") == environment


def test_every_demo_case_and_the_validation_cases_are_covered():
    names = [i["name"] for i in _load("ShopSense.postman_collection.json")["item"]]
    assert names[0] == "GET /health" and len(names) == 1 + len(CASES) + 3
    for n, (label, _msg, _cust) in enumerate(CASES, 1):
        assert names[n] == f"{n}. {label}"
    assert sum("rejected" in n for n in names) == 3


def test_each_request_asserts_something_and_uses_the_base_url_variable():
    for item in _load("ShopSense.postman_collection.json")["item"]:
        tests = [e for e in item["event"] if e["listen"] == "test"]
        assert tests and "pm.test(" in "\n".join(tests[0]["script"]["exec"]), item["name"]
        assert item["request"]["url"]["raw"].startswith("{{baseUrl}}/"), item["name"]
    assert _load("ShopSense.postman_environment.json")["values"][0]["key"] == "baseUrl"


def test_the_collection_carries_no_secrets_or_customer_pii():
    text = (DOCS / "ShopSense.postman_collection.json").read_text(encoding="utf-8")
    import re
    # key-shaped VALUES (the collection's own /health check mentions the words "gsk_" and "sk-" as patterns, which is fine)
    assert not re.search(r"(gsk_|sk-|sk-lf-|pk-lf-)[A-Za-z0-9_-]{16,}|AIza[A-Za-z0-9_-]{20,}|[\w.+-]+@[\w-]+\.\w+", text)


def test_embedded_scripts_compile_when_node_is_available():
    node = shutil.which("node")
    if not node:
        return
    collection = _load("ShopSense.postman_collection.json")
    events = list(collection["event"]) + [e for i in collection["item"] for e in i["event"]]
    for e in events:
        code = "\n".join(e["script"]["exec"])
        r = subprocess.run([node, "-e", "new Function('pm', require('fs').readFileSync(0,'utf8'))"], input=code, text=True, capture_output=True)
        assert r.returncode == 0, r.stderr[:300]
