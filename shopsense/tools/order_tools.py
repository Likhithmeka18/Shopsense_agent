"""
ShopSense Tools: order-domain tools for the support agent (Milestone 2).

Each tool is a plain Python function with a clear signature and docstring,
wrapped with retry/circuit-breaker/logging (tools/reliability.py), and
declared as a JSON-schema "function" so an LLM can call it through LiteLLM's
native tool-calling (the OpenAI-compatible `tools=` parameter). MockAPI
loads generated CSV data today; a real backend client can replace it later
without the tool signatures, schemas, or the agent loop changing at all --
the "swap the implementation, never touch the caller" idea (mock vs MCP).
"""
from __future__ import annotations

import csv
from pathlib import Path
from typing import Any

from .reliability import make_robust_tool

DATA_DIR = Path(__file__).resolve().parents[2] / "data" / "shopsense" / "mock_api"


def refund_tier_for_amount(amount_inr: float) -> str:
    """RF-3 approval tier for a refund amount. The single source of truth:
    calculate_refund_amount, Milestone 5's refund-review trigger, and
    Milestone 6's risk profile all call this, so the tier thresholds can
    never drift apart between the tool and the workflows built on it."""
    if amount_inr < 2000:
        return "auto"
    if amount_inr < 10000:
        return "manager_review"
    return "executive_review"


class MockAPI:
    """Loads the CSV tables generated by generate_tables.py."""

    def __init__(self, data_dir: Path = DATA_DIR):
        self.customers: dict[str, dict] = {}
        self.orders: dict[str, dict] = {}
        self.shipments: dict[str, dict] = {}
        self.refunds: dict[str, dict] = {}
        self._load(data_dir)

    def _load(self, data_dir: Path) -> None:
        with open(data_dir / "customers.csv") as f:
            for row in csv.DictReader(f):
                self.customers[row["customer_id"]] = row
        with open(data_dir / "orders.csv") as f:
            for row in csv.DictReader(f):
                self.orders[row["order_id"]] = row
        with open(data_dir / "shipments.csv") as f:
            for row in csv.DictReader(f):
                self.shipments[row["order_id"]] = row
        with open(data_dir / "refunds.csv") as f:
            for row in csv.DictReader(f):
                # one active refund per order is enough for this mock
                self.refunds.setdefault(row["order_id"], row)


def build_tools(api: MockAPI, *, robust: bool = True) -> tuple[dict[str, Any], list[dict]]:
    """Build (callables_by_name, tool_schemas) bound to one MockAPI instance.
    callables_by_name is what the agent loop executes; tool_schemas is what
    gets sent to the LLM so it knows what it can call.

    `robust=True` (the M2 agent path) wraps each tool in retry + circuit breaker. The ticket graph passes `robust=False` and puts ONE
    `DependencyGuard` around the whole read-only planning step instead, so a flaky order system is retried once, by one layer, and
    the failure is reported once -- not multiplied by two stacked retry loops."""
    wrap = make_robust_tool if robust else (lambda fn, _name, **_kw: fn)

    def order_lookup(order_id: str) -> dict:
        """Look up an order's status, total amount, and customer info."""
        if order_id not in api.orders:
            return {"error": f"Order {order_id} not found"}
        order = api.orders[order_id]
        customer = api.customers.get(order["customer_id"], {})
        return {
            "order_id": order["order_id"],
            "status": order["status"],
            "total_amount_inr": order["total_amount_inr"],
            "order_date": order["order_date"],
            "customer_name": customer.get("name"),
            "payment_method": order["payment_method"],
        }

    def refund_status(order_id: str) -> dict:
        """Check whether an order has an active refund request and its approval status."""
        refund = api.refunds.get(order_id)
        if not refund:
            return {"has_refund_request": False}
        return {
            "has_refund_request": True,
            "refund_id": refund["refund_id"],
            "amount_inr": refund["amount_inr"],
            "approval_tier": refund["approval_tier"],
            "approved": refund["approved"] in ("True", True),
            "reason": refund["reason"],
        }

    def shipping_tracker(order_id: str) -> dict:
        """Get shipment tracking info (carrier, tracking number, scan state) for an order."""
        shipment = api.shipments.get(order_id)
        if not shipment:
            return {"tracking_available": False, "reason": "Not yet shipped or no shipment on file"}
        return {
            "tracking_available": True,
            "carrier": shipment["carrier"],
            "tracking_number": shipment["tracking_number"],
            "scan_state": shipment["scan_state"],
        }

    def calculate_refund_amount(order_id: str) -> dict:
        """Determine refund eligibility and amount/approval tier for an order."""
        if order_id not in api.orders:
            return {"error": f"Order {order_id} not found"}
        order = api.orders[order_id]
        customer = api.customers.get(order["customer_id"], {})
        if customer.get("abuse_flag") in ("True", True):
            return {"eligible": False, "reason": "Customer has abuse flag; requires manager review"}
        amount = float(order["total_amount_inr"])
        return {"eligible": True, "refund_amount_inr": amount, "approval_tier": refund_tier_for_amount(amount)}

    callables = {
        "order_lookup": wrap(order_lookup, "order_lookup"),
        "refund_status": wrap(refund_status, "refund_status"),
        "shipping_tracker": wrap(shipping_tracker, "shipping_tracker"),
        "calculate_refund_amount": wrap(calculate_refund_amount, "calculate_refund_amount"),
    }

    schemas = [
        {
            "type": "function",
            "function": {
                "name": "order_lookup",
                "description": "Look up an order's status, total amount, and customer info.",
                "parameters": {
                    "type": "object",
                    "properties": {"order_id": {"type": "string", "description": "e.g. ORD-4001"}},
                    "required": ["order_id"],
                },
            },
        },
        {
            "type": "function",
            "function": {
                "name": "refund_status",
                "description": "Check whether an order has an active refund request and its approval status.",
                "parameters": {
                    "type": "object",
                    "properties": {"order_id": {"type": "string"}},
                    "required": ["order_id"],
                },
            },
        },
        {
            "type": "function",
            "function": {
                "name": "shipping_tracker",
                "description": "Get shipment tracking info (carrier, tracking number, scan state) for an order.",
                "parameters": {
                    "type": "object",
                    "properties": {"order_id": {"type": "string"}},
                    "required": ["order_id"],
                },
            },
        },
        {
            "type": "function",
            "function": {
                "name": "calculate_refund_amount",
                "description": "Determine refund eligibility and amount/approval tier for an order.",
                "parameters": {
                    "type": "object",
                    "properties": {"order_id": {"type": "string"}},
                    "required": ["order_id"],
                },
            },
        },
    ]
    return callables, schemas
