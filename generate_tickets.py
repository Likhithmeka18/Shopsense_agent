"""
ShopSense - Asset B generator: support tickets.
Intent categories borrowed from Bitext's real taxonomy (ORDER/DELIVERY/PRODUCT/REFUND/FEEDBACK).
Order IDs are drawn from the SAME table pool generated by generate_tables.py so M2 tool
lookups resolve correctly. Deliberately messy: missing fields, anger, injection attempts, etc.

Two layers (same discipline as generate_tables.py):
  * BASE (TCK-0001..0030): the original 30-ticket sample, produced by the global RNG exactly as before.
    Must stay byte-identical (tests/demos/docs cite it).
  * EXTENSION (TCK-0031..0120, extend_tickets): +90 tickets with their OWN RNG, APPEND-ONLY, drawn
    from the extension customers/orders. It adds what Data Sourcing Guidelines 4.4.2 asks for but
    30 tickets cannot contain: mild profanity, 1-in-6 missing order refs, refunds above the automated
    cap (some also angry), >= 6 legal threats, >= 8 varied injections, >= 4 safety reports, Hinglish /
    Indian English, plus the cases the capstone needs: repeat contacts (ESC-REPEAT), probes asking
    whether the account is flagged (must never be disclosed), questions the corpus deliberately cannot
    answer, category-specific return questions, abuse-flagged refund requests, and very short / very
    long messages. Extension ground_truth carries extra keys: scenario, expected_route,
    expected_escalation_codes, expected_behavior.
"""
