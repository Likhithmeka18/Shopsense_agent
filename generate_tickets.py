def rand_recent_date():
    d = random.randint(0, 10)
    h = random.randint(0, 23)
    return (REFERENCE_CLOCK - timedelta(days=d, hours=h)).strftime("%Y-%m-%dT%H:%M:%S")


def pick_order(pool, prefer_high_value=False):
    orders = pool["orders_detail"]
    if prefer_high_value:
        candidates = sorted(orders, key=lambda o: -o["total_amount_inr"])[:20]
        return random.choice(candidates)
    return random.choice(orders)


def make_ticket(tid, pool, special=None):
    intent = random.choice(list(TEMPLATES.keys()))
    category = INTENTS[intent]
    order = pick_order(pool, prefer_high_value=(special == "high_value_refund"))
    cust = next(c for c in pool["customers"] if c["customer_id"] == order["customer_id"])

    template = random.choice(TEMPLATES[intent])
    omit_order = random.random() < (1 / 6)  # ~1 in 6 missing order reference

    text = template.format(order="" if omit_order else order["order_id"], name=cust["name"])
    if omit_order:
        text = text.replace("  ", " ").strip()

    ground_truth = {
        "intent": intent,
        "category": category,
        "order_id": None if omit_order else order["order_id"],
        "customer_id": cust["customer_id"],
        "sentiment": "neutral",
        "urgency": "low",
        "requires_human_review": False,
        "contains_injection_attempt": False,
    }

    if special == "angry":
        text += random.choice(ANGRY_SUFFIXES)
        ground_truth["sentiment"] = "angry"
        ground_truth["urgency"] = "high"
    elif special == "legal_threat":
        text += random.choice(LEGAL_THREAT_SUFFIXES)
        ground_truth["sentiment"] = "angry"
        ground_truth["urgency"] = "high"
        ground_truth["requires_human_review"] = True
    elif special == "product_safety":
        text = random.choice(PRODUCT_SAFETY_TEMPLATES).format(order=order["order_id"])
        intent, category = "PRODUCT_DEFECTIVE", "PRODUCT"
        ground_truth.update({
            "intent": intent, "category": category, "order_id": order["order_id"],
            "sentiment": "concerned", "urgency": "critical", "requires_human_review": True,
        })
    elif special == "injection":
        text = random.choice(INJECTION_TEMPLATES).format(order=order["order_id"])
        ground_truth["contains_injection_attempt"] = True
        ground_truth["requires_human_review"] = True
    elif special == "indian_english":
        text = random.choice(INDIAN_ENGLISH_TEMPLATES).format(order=order["order_id"])
    elif special == "high_value_refund":
        text = random.choice(HIGH_VALUE_REFUND_TEMPLATES).format(order=order["order_id"])
        intent, category = "REFUND_REQUEST", "REFUND"
        ground_truth.update({
            "intent": intent, "category": category, "order_id": order["order_id"],
            "urgency": "medium", "requires_human_review": True,
        })

    return {
        "ticket_id": f"TCK-{tid:04d}",
        "channel": random.choice(CHANNELS),
        "created_at": rand_recent_date(),
        "customer_id": cust["customer_id"] if not omit_order else cust["customer_id"],
        "text": text,
        "ground_truth": ground_truth,
    }


